const camera = { x: 0, y: 0 };

// Мир -> экран (изометрическая проекция, TILE_W/TILE_H — из ground.js).
// Камера НЕ округляется до пикселя: на медленной скорости (разгон,
// торможение) округление давало сдвиги по целому пикселю через неровные
// промежутки — картинка «дрожала». Земля в drawGround() (render.js)
// использует ровно ту же дробную камеру, поэтому объекты и земля всегда
// сдвигаются вместе и друг относительно друга не ездят.
function toScreen(gx, gy) {
  return {
    x: (gx - gy) * (TILE_W / 2) - camera.x + canvas.width / 2,
    y: (gx + gy) * (TILE_H / 2) - camera.y + canvas.height / 2
  };
}
